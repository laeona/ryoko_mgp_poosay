export function getSpell(name: string): DnDSpell | undefined {
  return SPELLS.find((s) => s.name === name);
}

export function getSpellsByClass(className: string): DnDSpell[] {
  return SPELLS.filter((s) => s.classes.includes(className));
}

export function getSpellsByLevel(level: number): DnDSpell[] {
  return SPELLS.filter((s) => s.level === level);
}